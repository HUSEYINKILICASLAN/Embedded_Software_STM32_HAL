#include "max7219.h"	//header dosyasindaki tanimlamalari kullanabilmek icin yazildi


void MAX7219_Send_Data(SPI_HandleTypeDef *hspi, uint8_t reg, uint8_t data) {//veri gondermek icin gereken fonksiyon
	uint8_t buffer[2] = { reg, data };//gonderilecek data boyutu ayarlandi, register ve veri icerecek
	HAL_GPIO_WritePin(CS_GPIO_Port, CS_Pin, GPIO_PIN_RESET);//datasheet e gore veri gondermeden once cs pini reset yapilmali veri gonderilip set yapilmali
	HAL_SPI_Transmit(hspi, buffer, 2, HAL_MAX_DELAY);//register ve adres verileri birlikte gonderiliyor
	HAL_GPIO_WritePin(CS_GPIO_Port, CS_Pin, GPIO_PIN_SET);//datasheet e gore veri gonderimi sonrasi cs pini set edildi
	HAL_Delay(10);//biraz gecikme eklendi
}

void MAX7219_Init(SPI_HandleTypeDef *hspi) {//max7219 entegresinin baslangic ayarlari yapildi
	MAX7219_Send_Data(hspi, MAX7219_Shutdown, 0x01);//ekrani sabit birakmak ve mimimum tuketim modunu acmak icin kullanilir ama bu mod kapali secildi
	MAX7219_Send_Data(hspi, MAX7219_Decode_Mode, 0x00);//decode modu no decode olarak ayarlandi
	MAX7219_Send_Data(hspi, MAX7219_Intensity, 0x00);//led parlakligi minimum ayarlandi
	MAX7219_Send_Data(hspi, MAX7219_Scan_Limit, 0x07);//scan limit butun sutunlar oarak ayarlandi
	//MAX7219_Send_Data(hspi, MAX7219_Display_Test, 0x00);//test modundan cikarildi
	MAX7219_Clear(hspi);
}

void MAX7219_Clear(SPI_HandleTypeDef *hspi) {//butun ledleri sondurme fonksiyonu
	for (int i = 0; i < 8; i++) {//bu dongu ile 0x00 adresinden baslayarak 0x08 adresine kadar olan register lara 0 gonderip dogrudan ledlere 0 gonderip sonduruyor
		MAX7219_Send_Data(hspi, i+1, 0x00);//i+1 olmasinin nedeni digitlerin adreslerinin 1 ile 8 arasinda olmasidir
	}
}

void MAX7219_Display_Matrix(SPI_HandleTypeDef *hspi, const uint8_t *matrix) {//gondermek istedigimiz harf yada rakami goonderme fonksiyonu
	for (int i = 0; i < 8; i++) {
		MAX7219_Send_Data(hspi, i+1, matrix[i]);//i+1 olmasinin nedeni digitlerin adreslerinin 1 ile 8 arasinda olmasidir
	}
}

